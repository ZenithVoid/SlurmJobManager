        get => _remoteWorkDir;
        set
        {
            var expanded = ExpandHomePath(value);
            if (SetField(ref _remoteWorkDir, expanded))
            {
                OnPropertyChanged(nameof(RemoteWorkDirDisplay));
                OnPropertyChanged(nameof(TaskFilesRootPathDisplay));
                OnPropertyChanged(nameof(TaskContextWorkDirDisplay));
                OnPropertyChanged(nameof(TaskContextSummary));
                if (!_isAutoUpdatingRemoteWorkDir)
                {
                    var normalizedCurrent = NormalizeRemotePath(expanded);
                    var normalizedAuto = NormalizeRemotePath(BuildAutoRemoteWorkDir());
                    _remoteWorkDirFollowsTaskId =
                        string.IsNullOrWhiteSpace(normalizedCurrent)
                        || (!string.IsNullOrWhiteSpace(normalizedAuto)
                            && string.Equals(normalizedCurrent, normalizedAuto, StringComparison.Ordinal));
                }

                if (string.IsNullOrWhiteSpace(CurrentTaskFilesPath))
                {
                    CurrentTaskFilesPath = expanded;
                }

                TryScheduleLastTaskContextSave();
                NotifyTaskConfigurationChanged();
            }
        }
    }

