    private void TryAutoFillRemoteWorkDir()
    {
        var autoPath = BuildAutoRemoteWorkDir();
        if (string.IsNullOrWhiteSpace(autoPath))
            return;

        var current = NormalizeRemotePath(RemoteWorkDir);
        var previousAuto = NormalizeRemotePath(_lastAutoGeneratedRemoteWorkDir);

        var shouldFollow = string.IsNullOrWhiteSpace(current)
            || _remoteWorkDirFollowsTaskId
            || (!string.IsNullOrWhiteSpace(previousAuto)
                && string.Equals(current, previousAuto, StringComparison.Ordinal));

        _lastAutoGeneratedRemoteWorkDir = NormalizeRemotePath(autoPath);
        if (!shouldFollow)
            return;

        _isAutoUpdatingRemoteWorkDir = true;
        try
        {
            RemoteWorkDir = autoPath;
            CurrentTaskFilesPath = autoPath;
            _remoteWorkDirFollowsTaskId = true;
        }
        finally { _isAutoUpdatingRemoteWorkDir = false; }
    }

    private string BuildAutoRemoteWorkDir()
    {
        if (string.IsNullOrWhiteSpace(RootDirectory) || string.IsNullOrWhiteSpace(TaskId))
            return string.Empty;
        return NormalizeRemotePath($"{RootDirectory.TrimEnd('/')}/{TaskId}");
    }

    private bool CanCreateTaskIdDirectory()
        => !IsDisposed
           && !IsBusy
           && IsSshConnectedSafe()
           && !string.IsNullOrWhiteSpace(RootDirectory)
           && !string.IsNullOrWhiteSpace(TaskId)
           && _taskIdDirectoryExists == false;

    private async Task CreateCurrentTaskIdDirectoryAsync(CancellationToken ct)
    {
        await EnsureHomeDirectoryLoadedAsync(ct);

        if (!IsSshConnectedSafe())
        {
            SetStatus("Task.RequireConnection", "WarningTextStyle");
            return;
        }

        if (string.IsNullOrWhiteSpace(RootDirectory))
        {
            SetStatus("Task.RequireRootDirectory", "WarningTextStyle");
            return;
        }

        if (string.IsNullOrWhiteSpace(TaskId))
        {
            SetStatus("Task.RequireTaskId", "WarningTextStyle");
            return;
        }

        var normalizedTaskId = NormalizeTaskIdForRestore(TaskId);
        if (!string.Equals(normalizedTaskId, TaskId.Trim(), StringComparison.Ordinal))
        {
            SetStatus("Task.TaskIdInvalidForDirectoryCreate", "WarningTextStyle");
            return;
        }

        if (_taskIdDirectoryExists == true)
        {
            SetStatus("Task.TaskIdDirExists", "InfoTextStyle");
            return;
        }

        var targetPath = NormalizeRemotePath($"{RootDirectory.TrimEnd('/')}/{TaskId.Trim()}");
        if (string.IsNullOrWhiteSpace(targetPath))
        {
            SetStatus("Task.RequireTaskPath", "WarningTextStyle");
            return;
        }

        IsBusy = true;
        var refreshTaskIdDirectoryState = false;
        try
        {
            var (_, stderr, exitCode) = await _ssh.ExecuteAsync($"mkdir -p {EscapeShellArg(targetPath)}", ct);
            if (exitCode != 0)
            {
                var detail = string.IsNullOrWhiteSpace(stderr) ? L("Task.TaskIdDirCreateFailedNoDetail") : stderr.Trim();
                SetStatus(string.Format(L("Task.TaskIdDirCreateFailed"), detail), "ErrorTextStyle", localize: false);
                return;
            }

            refreshTaskIdDirectoryState = true;
            await RefreshTaskIdDirectoryStateAsync(ct);
            SetStatus(string.Format(L("Task.TaskIdDirCreateSucceeded"), CollapseHomePath(targetPath)), "SuccessTextStyle", localize: false);
        }
        catch (Exception ex)
        {
            SetStatus(string.Format(L("Task.TaskIdDirCreateFailed"), ex.Message), "ErrorTextStyle", localize: false);
        }
        finally
        {
            IsBusy = false;
            if (refreshTaskIdDirectoryState)
                CommandManager.InvalidateRequerySuggested();
        }
    }

    // ── TaskId directory existence validation ────────────────────────────────

    private void ScheduleTaskIdDirectoryCheck()
    {
        if (IsDisposed) return;
        _taskIdValidationCts?.Cancel();
        _taskIdValidationCts?.Dispose();
        _taskIdValidationCts = null;

        _taskIdDirectoryExists = null;
        TaskIdDirectoryStatus  = string.Empty;
        CommandManager.InvalidateRequerySuggested();

        if (!IsSshConnectedSafe()
            || string.IsNullOrWhiteSpace(RootDirectory)
            || string.IsNullOrWhiteSpace(TaskId))
        {
            return;
        }

        var cts            = new CancellationTokenSource();
        _taskIdValidationCts = cts;
        var capturedTaskId = TaskId;
        var capturedRoot   = RootDirectory;

        _ = Task.Run(async () =>
        {
            try { await Task.Delay(300, cts.Token); }
            catch (OperationCanceledException) { return; }

            if (cts.IsCancellationRequested) return;

            var path = $"{capturedRoot.TrimEnd('/')}/{capturedTaskId}";
            try
            {
                var exists = await _ssh.RemoteDirectoryExistsAsync(path, cts.Token);
                var dispatcher = Application.Current?.Dispatcher;
                if (dispatcher == null || dispatcher.HasShutdownStarted) return;
                dispatcher.Invoke(() =>
                {
                    if (cts.IsCancellationRequested || IsDisposed) return;
                    _taskIdDirectoryExists = exists;
                    TaskIdDirectoryStatus  = exists
                        ? L("Task.TaskIdDirExists")
                        : L("Task.TaskIdDirNotExists");
                    CommandManager.InvalidateRequerySuggested();
                });
            }
            catch (OperationCanceledException) { }
            catch (Exception ex)
            {
                var dispatcher = Application.Current?.Dispatcher;
                if (dispatcher == null || dispatcher.HasShutdownStarted) return;
                dispatcher.Invoke(() =>
                {
                    if (cts.IsCancellationRequested || IsDisposed) return;
                    _taskIdDirectoryExists = null;
                    TaskIdDirectoryStatus  = L("Task.TaskIdDirCheckFailed");
                    System.Diagnostics.Debug.WriteLine($"[TaskIdValidation] {ex.Message}");
                    CommandManager.InvalidateRequerySuggested();
                });
            }
        }, cts.Token);
    }

    private async Task RefreshTaskIdDirectoryStateAsync(CancellationToken ct)
    {
        if (IsDisposed)
            return;

        if (!IsSshConnectedSafe()
            || string.IsNullOrWhiteSpace(RootDirectory)
            || string.IsNullOrWhiteSpace(TaskId))
        {
            _taskIdDirectoryExists = null;
            TaskIdDirectoryStatus = string.Empty;
            CommandManager.InvalidateRequerySuggested();
            return;
        }

        var path = NormalizeRemotePath($"{RootDirectory.TrimEnd('/')}/{TaskId.Trim()}");
        try
        {
            var exists = await _ssh.RemoteDirectoryExistsAsync(path, ct);
            _taskIdDirectoryExists = exists;
            TaskIdDirectoryStatus = exists ? L("Task.TaskIdDirExists") : L("Task.TaskIdDirNotExists");
            CommandManager.InvalidateRequerySuggested();
        }
        catch (OperationCanceledException)
        {
        }
        catch (Exception ex)
        {
            _taskIdDirectoryExists = null;
            TaskIdDirectoryStatus = L("Task.TaskIdDirCheckFailed");
            System.Diagnostics.Debug.WriteLine($"[TaskIdValidation.Refresh] {ex.Message}");
            CommandManager.InvalidateRequerySuggested();
        }
    }

    // ── App candidates + pinning ─────────────────────────────────────────────

    private async Task RefreshAppCandidatesAsync(CancellationToken ct)
    {
        IsBusy = true;
        try
        {
            var all = new List<string>();
            foreach (var dir in AppSourceDirs)
            {
                try
                {
                    var files = await _ssh.ListFilesAsync(dir, ct);
                    all.AddRange(files.Select(f => $"{dir}/{f}"));
                }
                catch (Exception ex) { System.Diagnostics.Debug.WriteLine($"[TaskEditorViewModel] ListFilesAsync({dir}): {ex.Message}"); }
            }
            RebuildAppDisplayList(all);
        }
        catch (Exception ex) { SetStatus(string.Format(L("Task.RefreshAppCandidatesFailed"), ex.Message), "ErrorTextStyle", localize: false); }
        finally { IsBusy = false; }
    }

    private void RebuildAppDisplayList(IEnumerable<string>? allCandidates = null)
    {
        var existing = allCandidates ?? AppDisplayList.Where(x => !PinnedApps.Contains(x)).ToList();
        AppDisplayList.Clear();
        foreach (var p in PinnedApps)      AppDisplayList.Add(p);
        foreach (var c in existing.Where(c => !PinnedApps.Contains(c))) AppDisplayList.Add(c);
        RebuildFilteredAppList();
    }

    private void RebuildFilteredAppList()
    {
        var filter = _appPath;
        FilteredAppList.Clear();

        if (string.IsNullOrEmpty(filter) || AppDisplayList.Contains(filter))
        {
            foreach (var item in AppDisplayList) FilteredAppList.Add(item);
            return;
        }

        var lower    = filter.ToLowerInvariant();
        var prefix   = AppDisplayList.Where(x => x.ToLowerInvariant().StartsWith(lower)).OrderBy(x => x);
        var contains = AppDisplayList.Where(x =>  x.ToLowerInvariant().Contains(lower)
                                               && !x.ToLowerInvariant().StartsWith(lower)).OrderBy(x => x);
        foreach (var item in prefix.Concat(contains)) FilteredAppList.Add(item);
    }

    private void RebuildFilteredTemplateList()
    {
        var filter = _selectedTemplate;
        FilteredTemplateList.Clear();

        if (string.IsNullOrEmpty(filter) || TemplateDisplayList.Contains(filter))
        {
            foreach (var item in TemplateDisplayList) FilteredTemplateList.Add(item);
            return;
        }

        var lower    = filter.ToLowerInvariant();
        var prefix   = TemplateDisplayList.Where(x => x.ToLowerInvariant().StartsWith(lower)).OrderBy(x => x);
        var contains = TemplateDisplayList.Where(x =>  x.ToLowerInvariant().Contains(lower)
                                                    && !x.ToLowerInvariant().StartsWith(lower)).OrderBy(x => x);
        foreach (var item in prefix.Concat(contains)) FilteredTemplateList.Add(item);
    }

