    // ── Task directory file list ──────────────────────────────────────────────

    private async Task RefreshTaskFilesAsync(CancellationToken ct)
    {
        await EnsureHomeDirectoryLoadedAsync(ct);

        if (!IsSshConnectedSafe())
        {
            SetStatus("Task.RequireConnection", "WarningTextStyle");
            return;
        }

        var targetPath = NormalizeRemotePath(CurrentTaskFilesPath);
        if (string.IsNullOrWhiteSpace(targetPath))
            targetPath = NormalizeRemotePath(RemoteWorkDir);
        if (string.IsNullOrWhiteSpace(targetPath))
        {
            SetStatus("Task.RequireTaskPath", "WarningTextStyle");
            return;
        }

        IsBusy = true;
        try
        {
            var escapedPath = EscapeShellArg(targetPath);
            var (kindStdOut, _, kindExitCode) = await _ssh.ExecuteAsync(
                $"if [ -d {escapedPath} ]; then echo DIR; " +
                $"elif [ -f {escapedPath} ]; then echo FILE; else echo MISSING; fi", ct);

            var kind = kindStdOut.Trim();
            if (kindExitCode != 0 || kind == "MISSING")
            {
                SetStatus("Task.PathMissing", "ErrorTextStyle");
                return;
            }
            if (kind == "FILE")
            {
                SetStatus("Task.PathIsFile", "ErrorTextStyle");
                return;
            }

            var (stdout, stderr, exitCode) = await _ssh.ExecuteAsync(
                $"cd {escapedPath} && " +
                "for entry in .* *; do " +
                "if [ \"$entry\" = \".\" ] || [ \"$entry\" = \"..\" ] || [ ! -e \"$entry\" ]; then continue; fi; " +
                "if [ -d \"$entry\" ]; then kind=d; else kind=f; fi; " +
                "if stat -c '%Y' \"$entry\" >/dev/null 2>&1; then mtime=$(stat -c '%Y' \"$entry\"); " +
                "elif stat -f '%m' \"$entry\" >/dev/null 2>&1; then mtime=$(stat -f '%m' \"$entry\"); " +
                "else mtime=; fi; " +
                "printf '%s\t%s\t%s\\n' \"$entry\" \"$kind\" \"$mtime\"; " +
                "done", ct);

            TaskFiles.Clear();
            CurrentTaskFilesPath = targetPath;

            if (exitCode != 0)
            {
                var errDetail = stderr.Trim();
                SetStatus(string.IsNullOrEmpty(errDetail)
                    ? L("Task.DirReadFailedNoDetail")
                    : string.Format(L("Task.DirReadFailed"), errDetail), "ErrorTextStyle", localize: false);
                return;
            }

            var entries = stdout.Split('\n',
                StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
            var loadedEntries = new List<TaskFileEntry>(entries.Length);
            foreach (var entry in entries)
            {
                var parts = entry.Split('\t');
                if (parts.Length < 2)
                    continue;

                var name = parts[0];
                if (name == "." || name == "..") continue;
                var isDirectory = string.Equals(parts[1], "d", StringComparison.Ordinal);
                var remotePath = BuildRemotePath(targetPath, name);
                long? modifiedUnixTimeValue = null;
                if (parts.Length >= 3)
                {
                    if (long.TryParse(parts[2], NumberStyles.Integer, CultureInfo.InvariantCulture, out var parsedUnixTime))
                        modifiedUnixTimeValue = parsedUnixTime;
                }

                loadedEntries.Add(new TaskFileEntry(
                    name,
                    isDirectory,
                    remotePath,
                    CollapseHomePath(remotePath),
                    modifiedUnixTimeValue));
            }

            foreach (var fileEntry in BuildSortedTaskFileEntries(loadedEntries))
                TaskFiles.Add(fileEntry);

            SetStatus(TaskFiles.Count == 0
                ? L("Task.DirEmpty")
                : string.Format(L("Task.DirLoadedCount"), TaskFiles.Count), "InfoTextStyle", localize: false);
        }
        catch (Exception ex) { SetStatus(string.Format(L("Task.RefreshFilesFailed"), ex.Message), "ErrorTextStyle", localize: false); }
        finally { IsBusy = false; }
    }

