                await RefreshTaskFilesAsync(ct);
                SetStatus(
                    string.Format(L("Task.SavedRemoteAssets"), CollapseHomePath(CurrentTaskFilesPath)),
                    "SuccessTextStyle",
                    localize: false);
            }
            _logger?.Info($"Task save completed. TaskId='{TaskId}', LocalDir='{GetLocalTaskDir()}'.");
            CommitTaskConfigurationSnapshot();
            return true;
        }
        catch (Exception ex)
        {
            SetStatus(string.Format(L("Task.SaveFailed"), ex.Message), "ErrorTextStyle", localize: false);
            _logger?.Error($"Task save failed. TaskId='{TaskId}', Root='{RootDirectory}'.", ex);
            return false;
        }
        finally { IsBusy = false; }
    }

    private async Task LoadTaskAsync(CancellationToken ct)
    {
        if (!await ConfirmDiscardUnsavedChangesAsync("Task.UnsavedActionLoadTask", ct))
            return;
        if (!ValidateRootAndId()) return;
        IsBusy = true;
        SetStatus("Task.Loading", "InfoTextStyle");
        _logger?.Info($"Task load started. TaskId='{TaskId}', Root='{RootDirectory}'.");
        try
        {
            var workspace = await _storage.LoadWorkspaceAsync(LocalDataRoot, TaskId, ct);
            if (workspace == null)
            {
                // Try legacy path
                var record = await _storage.LoadAsync(LocalDataRoot, TaskId, ct);
                if (record == null) { SetStatus("Task.LoadNotFound", "WarningTextStyle"); return; }
                PauseTaskConfigurationDirtyTracking();
                ApplyTaskRecord(record);
                ResumeTaskConfigurationDirtyTracking(commitSnapshot: true);
                SetStatus(string.Format(L("Task.LoadedLegacy"), TaskId), "SuccessTextStyle", localize: false);
                return;
            }

            PauseTaskConfigurationDirtyTracking();
            ApplyWorkspace(workspace);
            ResumeTaskConfigurationDirtyTracking(commitSnapshot: true);
            SetStatus(string.Format(L("Task.WorkspaceLoaded"), TaskId, workspace.Tasks.Count), "SuccessTextStyle", localize: false);
            _logger?.Info($"Task load completed. TaskId='{TaskId}', UnitCount={workspace.Tasks.Count}.");
        }
        catch (Exception ex)
        {
            ResumeTaskConfigurationDirtyTracking(commitSnapshot: false);
            SetStatus(string.Format(L("Task.LoadFailed"), ex.Message), "ErrorTextStyle", localize: false);
            _logger?.Error($"Task load failed. TaskId='{TaskId}', Root='{RootDirectory}'.", ex);
        }
        finally { IsBusy = false; }
    }

    private void ApplyWorkspace(TaskWorkspace w)
    {
        TaskUnits.Clear();

        if (w.Tasks.Count == 0)
        {
            // No units in workspace — create a fresh default
            EnsureAtLeastOneTaskUnit();
            return;
        }

        if (w.Tasks.Count == 1)
        {
            // Exactly one unit — the happy path
            TaskUnits.Add(new TaskUnitViewModel(w.Tasks[0]));
            SelectedTaskUnit = TaskUnits[0];
            return;
        }

        // Legacy multi-unit workspace: prompt the user to pick one active unit.
        // All units are loaded internally but only the chosen one is used for editing/submitting.
        foreach (var unit in w.Tasks)
            TaskUnits.Add(new TaskUnitViewModel(unit));

        var names   = TaskUnits.Select((u, i) => $"{i + 1}. {u.TaskName}").ToArray();
        var prompt  = Application.Current?.TryFindResource("Task.MultiUnitPrompt") as string
                      ?? L("Task.MultiUnitPrompt");
        SetStatus(string.Format(prompt, string.Join("\n", names)), "InfoTextStyle", localize: false);

        // Default: use the first unit
        SelectedTaskUnit = TaskUnits[0];
    }

    private TaskWorkspace BuildWorkspace() => new()
    {
        TaskId   = TaskId,
        RootPath = LocalDataRoot,
        Tasks    = TaskUnits.Select(u => u.ToModel()).ToList(),
    };

    private async Task PersistWorkspaceAssetsToRemoteAsync(TaskWorkspace workspace, CancellationToken ct)
    {
        foreach (var unit in workspace.Tasks)
        {
            var workDir = ResolveWorkDirForPersist(unit, workspace);
            if (string.IsNullOrWhiteSpace(workDir))
                continue;

            var normalizedWorkDir = NormalizeRemotePath(workDir);
            var escapedWorkDir = EscapeShellArg(normalizedWorkDir);
            var (_, stderr, exitCode) = await _ssh.ExecuteAsync($"mkdir -p {escapedWorkDir}/logs", ct);
            if (exitCode != 0)
            {
                var detail = string.IsNullOrWhiteSpace(stderr) ? L("Task.RemoteWorkDirPrepareFailedNoDetail") : stderr.Trim();
                throw new InvalidOperationException(detail);
            }

            _ = await MaterializeUnitParamFilesToWorkDirAsync(unit, normalizedWorkDir, ct);
            var stableSbatchPath = $"{normalizedWorkDir.TrimEnd('/')}/submit.sbatch";
            var stableSbatchContent = !string.IsNullOrWhiteSpace(unit.SbatchTemplate)
                ? unit.SbatchTemplate!
                : SbatchTemplate;
            await _ssh.WriteTextFileAsync(stableSbatchPath, stableSbatchContent, ct);
        }
    }

    private static string ResolveWorkDirForPersist(TaskUnit unit, TaskWorkspace workspace)
    {
        if (!string.IsNullOrWhiteSpace(unit.RemoteWorkDirectory))
            return unit.RemoteWorkDirectory.Trim();
        var candidate = workspace.Tasks
            .Select(u => u.RemoteWorkDirectory)
            .FirstOrDefault(path => !string.IsNullOrWhiteSpace(path));
        if (!string.IsNullOrWhiteSpace(candidate))
            return candidate.Trim();
        return string.Empty;
    }

    private async Task<List<string>> MaterializeUnitParamFilesToWorkDirAsync(TaskUnit unit, string normalizedWorkDir, CancellationToken ct)
    {
        var result = new List<string>();
        var allParamPaths = unit.ParameterFiles
            .Select(p => p.FilePath)
            .Concat(unit.CommandEntries.SelectMany(c => c.ParameterFiles))
            .Where(path => !string.IsNullOrWhiteSpace(path))
            .Distinct(StringComparer.Ordinal)
            .ToList();

        foreach (var rawPath in allParamPaths)
        {
            var path = rawPath.Trim();
            var fileName = GetRemoteFileNameFromPath(path);
            if (string.IsNullOrWhiteSpace(fileName))
                continue;

            var targetPath = $"{normalizedWorkDir.TrimEnd('/')}/{fileName}";
            var normalizedSource = NormalizeRemotePath(path);
            var sourceIsAbsolute = normalizedSource.StartsWith("/", StringComparison.Ordinal);
            var sourcePath = sourceIsAbsolute ? normalizedSource : targetPath;
            var samePath = string.Equals(sourcePath, NormalizeRemotePath(targetPath), StringComparison.Ordinal);
            if (!samePath)
            {
                var (_, copyErr, copyExit) = await _ssh.ExecuteAsync(
                    $"cp -- {EscapeShellArg(sourcePath)} {EscapeShellArg(targetPath)}",
                    ct);
                if (copyExit != 0)
                {
                    var detail = string.IsNullOrWhiteSpace(copyErr) ? L("Task.ParamCopyFailedNoDetail") : copyErr.Trim();
                    throw new InvalidOperationException(string.Format(L("Task.ParamCopyFailed"), detail));
                }
            }

            if (!result.Contains(targetPath, StringComparer.Ordinal))
                result.Add(targetPath);
        }

        return result;
    }

